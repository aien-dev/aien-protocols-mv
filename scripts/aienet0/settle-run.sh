# Host-test orchestration, not a production signer or Core RPC implementation.
# Restored from evidence/aienet0-20261028/settlement/settle-run.sh.at-run
# (sha256 fc2f07e12a973a4496cb3f8b24f3a0c7d4ff04232e5c8f74efd3680dee7a1ef9).
# usage: settle-run.sh FRESH_EVIDENCE_DIR [honest|tampered-receipt|tampered-attestation]
# Existing carrier env: RUN SERVE LISTEN CONNECT KEYS PINS RECOMPUTE RECOMPUTE_SHA256
# WKEYS WPINS WSTATE. Core v2 env: LEDGER AUTHORITY ISSUER_KEY VERIFIER_KEY QUOTE.
# AUTHORITY is an externally provisioned v2 config, not generated by this script.
# QUOTE is exactly: quote tur-ledger-2 requester provider verifier 40 27 3 10 (no LF).
# Its SHA-256 is the configured policy pin for this bounded test profile.
# The issuer and verifier private keys are separate test-only P-256 PEM files, in tmpfs.
# OpenSSL 3.0.13 is the independent test-signing oracle, not a ledger dependency.
# Public authorization bytes/signatures are retained in evidence; private keys never are.
set -u
E=${1:?usage: settle-run.sh FRESH_EVIDENCE_DIR [honest|tampered-receipt|tampered-attestation]}
MODE=${2:-honest}
case $MODE in
  honest|tampered-attestation) SX= ;;
  tampered-receipt) SX='--misbehave tamper-receipt' ;;
  *) echo "unknown mode $MODE" >&2; exit 2 ;;
esac
for v in RUN SERVE LISTEN CONNECT KEYS PINS RECOMPUTE RECOMPUTE_SHA256 WKEYS WPINS WSTATE LEDGER AUTHORITY ISSUER_KEY VERIFIER_KEY QUOTE; do
  eval "x=\${$v:-}"
  [ -n "$x" ] || { echo "settle-run.sh: set $v" >&2; exit 2; }
done
D=$E/$MODE
J=$D/journal
if [ -e "$D" ]; then echo "settle-run.sh: $D exists; use a fresh evidence dir" >&2; exit 2; fi
umask 077
mkdir -p "$J" "$D/out"
T=$D/transcript.txt
: >"$T"
pending=no
sp=
step() {
  name=$1; shift
  printf '$ %s\n' "$*" >>"$T"
  "$@" >"$D/$name.out" 2>&1
  rc=$?
  cat "$D/$name.out" >>"$T"
  printf 'rc=%s\n\n' "$rc" >>"$T"
}
note() { printf '# %s\n' "$*" >>"$T"; }
sha() { sha256sum "$1" | cut -d' ' -f1; }
jsha() { sha "$J/journal"; }
fail() { note "RESULT FAIL $MODE: $*"; cat "$T"; echo "RESULT FAIL $MODE: $*"; exit 1; }
pubhex() { openssl pkey -in "$1" -pubout -outform DER 2>/dev/null | od -An -v -tx1 | tr -d ' \n' | cut -c53-; }
identity() { printf '%s' "$1" | xxd -r -p | sha256sum | cut -d' ' -f1; }
field() { cut -d' ' -f"$1" "$J/authority"; }
# Canonical bytes match Core #794: config LF body LF [reserve-authorization-digest LF].
# This is test orchestration of external signers; all verification/admission is native Omega.
auth_step() {
  auth_name=$1; shift
  body=$*
  message=$D/$auth_name.authorization
  { cat "$J/authority"; printf '\n%s\n' "$body"; case $1 in settle|refund) printf '%s\n' "$(sha "$D/reserve.authorization")" ;; esac; } >"$message"
  openssl dgst -sha256 -sign "$ISSUER_KEY" -out "$D/$auth_name.issuer.der" "$message" || { rc=3; note "issuer signing failed: $auth_name"; return 1; }
  isig=$(od -An -v -tx1 "$D/$auth_name.issuer.der" | tr -d ' \n')
  if [ "$1" = settle ]; then
    openssl dgst -sha256 -sign "$VERIFIER_KEY" -out "$D/$auth_name.verifier.der" "$message" || { rc=3; note "verifier signing failed: $auth_name"; return 1; }
    vsig=$(od -An -v -tx1 "$D/$auth_name.verifier.der" | tr -d ' \n')
    step "$auth_name" "$LEDGER" --journal "$J" "$@" "$isig" "$vsig"
  else
    step "$auth_name" "$LEDGER" --journal "$J" "$@" "$isig"
  fi
}

# A failed/ambiguous reserve or settle response must not silently strand escrow.
# Query the native journal under its lock; refund only an actually open job.
reconcile_exit() {
  local status=$? kind jid phase rest
  trap - EXIT HUP INT TERM
  if [ -n "$sp" ]; then kill "$sp" 2>/dev/null || true; wait "$sp" 2>/dev/null || true; fi
  [ "$pending" = yes ] || exit "$status"
  step recovery-show "$LEDGER" --journal "$J" show "$dag"
  kind=; jid=; phase=
  read -r kind jid phase rest <"$D/recovery-show.out" || true
  if [ "$rc" = 0 ] && [ "$kind" = job ] && [ "$jid" = "$dag" ] && [ "$phase" = reserved ]; then
    note "recovery: open reservation $dag -> signed refund"
    auth_step recovery-refund refund "$dag"
    step recovery-show "$LEDGER" --journal "$J" show "$dag"
    kind=; jid=; phase=
    read -r kind jid phase rest <"$D/recovery-show.out" || true
  fi
  if [ "$rc" = 0 ] && [ "$kind" = job ] && [ "$jid" = "$dag" ] && { [ "$phase" = settled ] || [ "$phase" = refunded ]; }; then
    note "RECOVERY closed JOB $dag phase $phase JOURNAL $J"
    echo "RECOVERY closed JOB $dag phase $phase JOURNAL $J" >&2
  elif [ "$rc" = 8 ]; then
    note "RECOVERY no-reservation JOB $dag JOURNAL $J"
    echo "RECOVERY no-reservation JOB $dag JOURNAL $J" >&2
  else
    note "RECOVERY REQUIRED JOB $dag JOURNAL $J"
    echo "RECOVERY REQUIRED JOB $dag JOURNAL $J; native state/refund unavailable, operator reconciliation required" >&2
  fi
  exit "$status"
}
trap reconcile_exit EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

note "HOST_TESTED $MODE, $(date -u +%Y-%m-%dT%H:%M:%SZ)"
note "ledger $LEDGER sha256 $(sha "$LEDGER"); run $RUN sha256 $(sha "$RUN")"
note "$(openssl version); test oracle only, no production key or independent-operator qualification"
cp "$AUTHORITY" "$J/authority" || fail 'copy authority'
cp "$QUOTE" "$D/quote" || fail 'copy published quote'
[ "$(field 1) $(field 2)" = 'genesis tur-ledger-2' ] || fail 'not a v2 authority'
[ "$(field 7) $(field 8) $(field 9)" = 'requester provider verifier' ] || fail 'account policy differs'
[ "$(pubhex "$ISSUER_KEY")" = "$(field 4)" ] || fail 'issuer key differs from pin'
[ "$(pubhex "$VERIFIER_KEY")" = "$(field 5)" ] || fail 'verifier key differs from pin'
printf '%s' 'quote tur-ledger-2 requester provider verifier 40 27 3 10' | cmp -s - "$D/quote" || fail 'unapproved quote'
quote=$(sha "$D/quote")
[ "$quote" = "$(field 6)" ] || fail 'quote differs from bounded policy pin'
step requester-identities "$RUN" keys --keys "$KEYS"
[ $rc = 0 ] || fail 'requester identities'
owner=$(awk '$1 == "submitter.p256" {print $2}' "$D/requester-identities.out")
vnode=$(awk '$1 == "verifier.p256" {print $2}' "$D/requester-identities.out")
pnode=$(cat "$PINS/volunteer.ed25519")
[ "$(identity "$owner")" = "$(field 10)" ] && [ "$(identity "$pnode")" = "$(field 11)" ] && [ "$(identity "$vnode")" = "$(field 12)" ] || fail 'owner/node identity mapping differs'
auth_step prefund prefund pf-1 requester 100
[ $rc = 0 ] || fail "prefund rc=$rc"
step bundle "$RUN" bundle --keys "$KEYS" --out "$D/out/job.an0b"
[ $rc = 0 ] || fail "bundle rc=$rc"
dag=$(awk '$1 == "BUNDLE" { print $2 }' "$D/bundle.out")
[ -n "$dag" ] || fail 'no BUNDLE line'
pending=yes
note "reservation intent JOB $dag JOURNAL $J; reconcile this native job if the adapter is interrupted"
auth_step reserve reserve "$dag" requester provider verifier 40 "$quote"
[ $rc = 0 ] || fail "reserve rc=$rc"

scmd="$SERVE $SX --connect $CONNECT --keys $WKEYS --pins $WPINS --state $WSTATE --connect-timeout 60"
note "serve: $scmd"
$scmd >"$D/serve.out" 2>"$D/serve.err" </dev/null &
sp=$!
step run "$RUN" run --resend "$D/out/job.an0b" --listen "$LISTEN" --keys "$KEYS" --pins "$PINS" --out "$D/out" --recompute "$RECOMPUTE" --recompute-sha256 "$RECOMPUTE_SHA256" --accept-timeout 90
run_rc=$rc
wait $sp
src=$?
sp=
note "serve rc=$src stdout: $(cat "$D/serve.out")"
note "serve stderr: $(tr '\n' ' ' <"$D/serve.err")"
vline=$(grep '^VERIFIED ' "$D/run.out")
vdag=$(printf '%s\n' "$vline" | awk '{print $2}')
vrcpt=$(printf '%s\n' "$vline" | awk '{print $3}')
authorized=no
check_rc=not-run
if [ "$run_rc" = 0 ] && [ "$vdag" = "$dag" ] && [ -n "$vrcpt" ]; then
  if [ "$MODE" = tampered-attestation ]; then
    old=$(od -An -tu1 -j172 -N1 "$D/out/$dag.mjv" | tr -d ' ')
    if [ "$old" = 0 ]; then byte='\001'; else byte='\000'; fi
    printf "$byte" | dd of="$D/out/$dag.mjv" bs=1 seek=172 count=1 conv=notrunc 2>/dev/null || fail 'mutate AN0V signature'
  fi
  step artifact-check "$RUN" check --bundle "$D/out/$dag.an0b" --mjr1 "$D/out/$dag.mjr1" --mjv "$D/out/$dag.mjv" --keys "$KEYS" --pins "$PINS"
  check_rc=$rc
  if [ "$check_rc" = 0 ] && [ "$(cat "$D/artifact-check.out")" = "CHECKED $dag $vrcpt" ] && [ "$(sha "$D/out/$dag.mjr1")" = "$vrcpt" ] && cmp -s "$D/out/job.an0b" "$D/out/$dag.an0b"; then authorized=yes; fi
fi
if [ "$authorized" = yes ]; then
  jobsha=$(sha "$D/out/job.an0b")
  verdictsha=$(sha "$D/out/$dag.mjv")
  note "decision: independently rechecked artifacts $dag -> signed settle"
  auth_step settle settle "$dag" "$vrcpt" 27 3 10 "$jobsha" "$verdictsha"
  [ $rc = 0 ] || fail "settle rc=$rc"
  before=$(jsha)
  auth_step settle-again settle "$dag" "$vrcpt" 27 3 10 "$jobsha" "$verdictsha"
  after=$(jsha)
  note "journal sha256 before repeat $before after $after"
  [ $rc = 0 ] && grep -q '^already-settled ' "$D/settle-again.out" || fail "repeat settle rc=$rc"
  [ "$before" = "$after" ] || fail 'repeat settle changed journal'
  decision=settled
else
  note "decision: not authorized (run rc=$run_rc check rc=$check_rc) -> signed refund"
  auth_step refund refund "$dag"
  [ $rc = 0 ] || fail "refund rc=$rc"
  decision=refunded
fi
step audit "$LEDGER" --journal "$J" audit
[ $rc = 0 ] || fail "audit rc=$rc"
step show "$LEDGER" --journal "$J" show "$dag"
bal=
for a in requester provider verifier; do
  step "balance-$a" "$LEDGER" --journal "$J" balance "$a"
  [ $rc = 0 ] || fail "balance $a rc=$rc"
  bal="$bal $(awk '{print $3}' "$D/balance-$a.out")"
done
bal=${bal# }
settles=$(awk '$3 == "settle"' "$J/journal" | wc -l | tr -d ' ')
note "decision $decision, balances requester provider verifier: $bal, settle records: $settles"
(cd "$D" && sha256sum journal/authority journal/journal quote *.authorization *.der out/*) >"$D/SHA256SUMS"
case $MODE in
  honest) want_decision=settled; want_bal='70 27 3'; want_settles=1; [ "$run_rc" = 0 ] && [ "$check_rc" = 0 ] || fail 'honest artifact verification did not run' ;;
  tampered-receipt) want_decision=refunded; want_bal='100 0 0'; want_settles=0; [ "$run_rc" = 12 ] && grep -q 'REFUSED MJB_' "$D/run.out" || fail 'receipt mutation not detected by parser' ;;
  tampered-attestation) want_decision=refunded; want_bal='100 0 0'; want_settles=0; [ "$run_rc" = 0 ] && [ "$check_rc" = 14 ] && grep -q 'AN0_BAD_COUNTERSIGN' "$D/artifact-check.out" || fail 'AN0V mutation not detected by verifier' ;;
esac
[ "$decision" = "$want_decision" ] || fail "decision $decision, want $want_decision"
[ "$bal" = "$want_bal" ] || fail "balances $bal, want $want_bal"
[ "$settles" = "$want_settles" ] || fail "settles $settles, want $want_settles"
pending=no
note "RESULT PASS $MODE: $decision, balances $bal"
cat "$T"
echo "RESULT PASS $MODE: $decision $dag, balances requester provider verifier $bal"
